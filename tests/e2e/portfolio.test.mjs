import { chromium, BASE, OUT, LAUNCH } from '../helpers.mjs';
const out = OUT; const B = BASE;
const b = await chromium.launch(LAUNCH);
let pass = 0, fail = 0; const ok = (c, m) => { c ? pass++ : (fail++, console.log('FAIL:', m)); };
const errs = [];
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
p.on('pageerror', e => errs.push(e.message));
p.on('console', m => { if (m.type() === 'error' && !/fonts\.g|TUNNEL|ERR_/.test(m.text())) errs.push(m.text()); });
const h1 = () => p.textContent('h1');

// 1. URL direta e atualização (fallback _redirects)
for (const [url, expect] of [['/demos/gestao360', 'Gestão360'], ['/projetos/gestao360', 'Gestão360'], ['/', 'Sites, sistemas'], ['/projetos/prime-imoveis', 'Prime Imóveis']]) {
  await p.goto(B + url); await p.waitForTimeout(400);
  ok((await h1()).includes(expect), `URL direta ${url}`);
  await p.reload(); await p.waitForTimeout(400);
  // no Netlify, /projetos/<slug> é entregue com barra final (301 para /projetos/<slug>/)
  ok((await h1()).includes(expect) && [url, url + '/'].includes(new URL(p.url()).pathname), `atualizar ${url}`);
}
await p.goto(B + '/demos/gestao360'); await p.waitForTimeout(300);
ok(await p.$('.g360-root') && !(await p.$('footer.on-dark')), 'demo sem cabeçalho/rodapé do portfólio');
// demos pendentes continuam no DemoPending
await p.goto(B + '/demos/arena-store'); await p.waitForTimeout(300);
ok((await h1()) === 'Todos os produtos' && await p.$('.as-root'), 'Arena Store em /demos/arena-store');
await p.goto(B + '/demos/outra-coisa'); await p.waitForTimeout(300);
ok((await h1()) === 'Esta página não existe', 'demos/* desconhecido → 404');
await p.goto(B + '/xyz'); await p.waitForTimeout(300);
ok((await h1()) === 'Esta página não existe', '404 geral');

// 2. Botões na página inicial
await p.goto(B + '/'); await p.waitForTimeout(400);
const art = p.locator('article', { has: p.locator('h3', { hasText: 'Gestão360' }) });
const demoLink = art.getByRole('link', { name: 'Testar demonstração' });
const detailLink = art.getByRole('link', { name: 'Ver detalhes', exact: true });
ok(await demoLink.getAttribute('href') === '/demos/gestao360', 'Testar demonstração → /demos/gestao360');
ok(await detailLink.getAttribute('href') === '/projetos/gestao360', 'Ver detalhes → /projetos/gestao360');
const pending = await p.$$eval('#projetos article', as => as.map(a => [a.querySelector('h3').textContent, a.textContent.includes('Demonstração em produção'), !!a.querySelector('a[href^="/demos/"]')]));
console.log('status:', JSON.stringify(pending));
ok(pending.length === 5 && pending.every(x => !x[1] && x[2]), 'os 5 projetos com link de demonstração e sem aviso "em produção"');
ok(JSON.stringify(pending.map(x => x[0])) === '["Prime Imóveis","Gestão360","Nova Serviços","Arena Store","OrçaFácil"]', 'os 4 projetos originais mantidos, OrçaFácil em 5º');
const ofArt = p.locator('article', { has: p.locator('h3', { hasText: 'OrçaFácil' }) });
ok(await ofArt.getByRole('link', { name: 'Testar demonstração' }).getAttribute('href') === '/demos/orcafacil', 'OrçaFácil: Testar demonstração → /demos/orcafacil');
ok(await ofArt.getByRole('link', { name: 'Ver detalhes', exact: true }).getAttribute('href') === '/projetos/orcafacil', 'OrçaFácil: Ver detalhes → /projetos/orcafacil');
ok((await ofArt.textContent()).includes('Projeto demonstrativo') && (await ofArt.textContent()).includes('Calculadora comercial'), 'OrçaFácil: selo demonstrativo e categoria');
const ofImg = await p.$eval('#projetos-orcafacil img', i => [i.getAttribute('loading'), i.getAttribute('src'), i.alt]);
ok(ofImg[1].startsWith('/projetos/orcafacil/tela-1') && ofImg[2].length > 10, 'OrçaFácil: captura real carregada com texto alternativo');
ok((await p.$$eval('footer a[href="/projetos/orcafacil"]', a => a.length)) === 1, 'OrçaFácil no rodapé');
await ofArt.getByRole('link', { name: 'Testar demonstração' }).click(); await p.waitForTimeout(400);
ok(new URL(p.url()).pathname === '/demos/orcafacil' && await p.$('.orca-root'), 'OrçaFácil: card → demo');
await p.goto(B + '/projetos/orcafacil'); await p.waitForTimeout(400);
const ofText = await p.textContent('main');
ok((await h1()) === 'OrçaFácil' && ofText.includes('Testar demonstração') && ofText.includes('Proposta para imprimir ou salvar em PDF pelo navegador') && !(await p.$('.orca-root')), 'OrçaFácil detalhes: página separada e textos coerentes');
await p.getByRole('link', { name: 'Testar demonstração' }).first().click(); await p.waitForTimeout(400);
ok(new URL(p.url()).pathname === '/demos/orcafacil', 'OrçaFácil detalhes → demo');
await p.goto(B + '/'); await p.waitForTimeout(400);
const asArt = p.locator('article', { has: p.locator('h3', { hasText: 'Arena Store' }) });
ok(await asArt.getByRole('link', { name: 'Testar demonstração' }).getAttribute('href') === '/demos/arena-store', 'Arena: Testar demonstração → /demos/arena-store');
ok(await asArt.getByRole('link', { name: 'Ver detalhes', exact: true }).getAttribute('href') === '/projetos/arena-store', 'Arena: Ver detalhes → /projetos/arena-store');
await asArt.getByRole('link', { name: 'Testar demonstração' }).click(); await p.waitForTimeout(400);
ok(new URL(p.url()).pathname === '/demos/arena-store' && await p.$('.as-root'), 'Arena: card → demo');
await p.goto(B + '/projetos/arena-store'); await p.waitForTimeout(400);
const asText = await p.textContent('main');
ok(asText.includes('Testar demonstração') && !asText.includes('Demonstração em produção') && asText.includes('Checkout identificado como simulação, sem pagamento') && !(await p.$('.as-root')), 'Arena detalhes: página explicativa separada, botão ativo e textos coerentes');
await p.goto(B + '/'); await p.waitForTimeout(400);
const nsArt = p.locator('article', { has: p.locator('h3', { hasText: 'Nova Serviços' }) });
ok(await nsArt.getByRole('link', { name: 'Testar demonstração' }).getAttribute('href') === '/demos/nova-servicos', 'Nova: Testar demonstração → /demos/nova-servicos');
ok(await nsArt.getByRole('link', { name: 'Ver detalhes', exact: true }).getAttribute('href') === '/projetos/nova-servicos', 'Nova: Ver detalhes → /projetos/nova-servicos');
await nsArt.getByRole('link', { name: 'Testar demonstração' }).click(); await p.waitForTimeout(400);
ok(new URL(p.url()).pathname === '/demos/nova-servicos' && await p.$('.ns-root'), 'Nova: card → demo');
await p.goto(B + '/projetos/nova-servicos'); await p.waitForTimeout(400);
const nsText = await p.textContent('main');
ok(nsText.includes('Testar demonstração') && !nsText.includes('Demonstração em produção') && nsText.includes('Mensagem do pedido pronta para copiar') && !nsText.includes('Envio por e-mail ou WhatsApp'), 'Nova detalhes: botão ativo e textos coerentes');
await p.goto(B + '/'); await p.waitForTimeout(400);
const pi = p.locator('article', { has: p.locator('h3', { hasText: 'Prime Imóveis' }) });
ok(await pi.getByRole('link', { name: 'Testar demonstração' }).getAttribute('href') === '/demos/imoveis', 'Prime: Testar demonstração → /demos/imoveis');
ok(await pi.getByRole('link', { name: 'Ver detalhes', exact: true }).getAttribute('href') === '/projetos/prime-imoveis', 'Prime: Ver detalhes → /projetos/prime-imoveis');
await pi.getByRole('link', { name: 'Testar demonstração' }).click(); await p.waitForTimeout(400);
ok(new URL(p.url()).pathname === '/demos/imoveis' && await p.$('.pi-root'), 'Prime: card → demo');
await p.goto(B + '/projetos/prime-imoveis'); await p.waitForTimeout(400);
const piText = await p.textContent('main');
ok(piText.includes('Testar demonstração') && !piText.includes('Demonstração em produção'), 'Prime detalhes: botão ativo');
ok(piText.includes('Mensagem de consulta pronta para copiar') && !piText.includes('Botão de contato em cada imóvel') && !piText.includes('galeria de fotos'), 'Prime detalhes: textos coerentes');
await p.getByRole('link', { name: 'Testar demonstração' }).first().click(); await p.waitForTimeout(400);
ok(new URL(p.url()).pathname === '/demos/imoveis', 'Prime detalhes → demo');
await p.goto(B + '/'); await p.waitForTimeout(400);
ok(pending.find(x => x[0] === 'Gestão360')[1] === false, 'Gestão360 sem aviso "em produção"');
await demoLink.click(); await p.waitForTimeout(400);
ok(new URL(p.url()).pathname === '/demos/gestao360' && await p.$('.g360-root'), 'clique abre a demo');
ok((await p.evaluate(() => scrollY)) === 0, 'demo abre no topo da página');
await p.goBack(); await p.waitForTimeout(400);
await p.locator('article', { has: p.locator('h3', { hasText: 'Gestão360' }) }).getByRole('link', { name: 'Ver detalhes', exact: true }).click(); await p.waitForTimeout(400);
ok(new URL(p.url()).pathname === '/projetos/gestao360', 'clique em Ver detalhes abre a página do projeto');
// 3. Página de detalhes
const detailText = await p.textContent('main');
ok(detailText.includes('Testar demonstração') && !detailText.includes('Demonstração em produção'), 'detalhes: botão Testar demonstração');
ok(!/Recharts|lucro e vendas|Vendas/.test(detailText), 'detalhes sem promessas antigas (Recharts, lucro e vendas)');
ok(detailText.includes('30 dias, 90 dias e 12 meses'), 'detalhes descrevem filtros reais');
await p.screenshot({ path: out + '/detail-g360.png' });
await p.getByRole('link', { name: 'Testar demonstração' }).first().click(); await p.waitForTimeout(400);
ok(new URL(p.url()).pathname === '/demos/gestao360', 'detalhes → demo');
// 4. Navegação de volta da demo
await p.click('.g360-brand'); await p.waitForTimeout(2000);
ok(new URL(p.url()).pathname === '/' && p.url().endsWith('#projetos'), 'logo da demo → /#projetos');
const top = await p.evaluate(() => Math.round(document.getElementById('projetos').getBoundingClientRect().top));
ok(top >= 0 && top < 200, `rolou até Projetos (top=${top})`);
await p.goto(B + '/demos/gestao360'); await p.waitForTimeout(300);
await p.click('.g360-top-kicker >> text=Alto Code'); await p.waitForTimeout(400);
ok(new URL(p.url()).pathname === '/' && !p.url().includes('#'), 'breadcrumb Alto Code → início');
await p.goto(B + '/demos/gestao360'); await p.waitForTimeout(300);
await p.click('.g360-footer a'); await p.waitForTimeout(400);
ok(new URL(p.url()).pathname === '/projetos/gestao360', 'rodapé da demo → detalhes');
// 5. Prévia do card coerente com a demo (12 meses)
await p.goto(B + '/'); await p.waitForTimeout(300);
await p.evaluate(async () => { for (let y = 0; y < document.body.scrollHeight; y += 500) { scrollTo({ top: y, behavior: 'instant' }); await new Promise(r => setTimeout(r, 40)); } });
await p.waitForTimeout(500);
const caps = await p.$$eval('#projetos article', as => as.map(a => { const i = a.querySelector('img'); return [a.id, !!i && i.complete && i.naturalWidth > 0, i && i.getAttribute('src')]; }));
ok(caps.length === 5 && caps.every(([id, okk, src]) => okk && src.includes(id.replace('projetos-', ''))), 'as 5 capturas reais carregam ' + JSON.stringify(caps.map(c => c[1])));
console.log('erros de console:', errs);
console.log(`\n${pass} passaram, ${fail} falharam`);
await b.close(); if (fail || errs.length) process.exit(1);
