const TEXT: Record<Locale, OrcaText> = { pt, en };

/** Textos e formatadores do OrçaFácil no idioma da página. */
export function useOrca() {
  const { locale, lp } = useLocale();
  return {
    locale,
    lp,
    t: TEXT[locale],
    money: (cents: number) => money(cents, locale),
    qty: (qty: number, unit: UnitId) => formatQty(qty, unit, locale),
    percent: (bp: number) => formatPercent(bp, locale),
    multiplier: (bp: number) => formatMultiplier(bp, locale),
    date: (d: Date) => formatDate(d, locale),
    unit: (u: UnitId) => unitText(u, locale),
    name: (item: CatalogItem) => itemName(item, locale),
    opt: (v: VariableId, o: Option) => optionText(v, o, locale),
    variable: (v: VariableId) => variableLabel(v, locale),
    spec: (r: Breakdown) => specLine(r, locale),
    toInput: (cents: number) => centsToInput(cents, locale),
  };
}
