const TEXT: Record<Locale, PiText> = { pt, en };

export function usePi() {
  const { locale, lp } = useLocale();
  return {
    locale,
    lp,
    t: TEXT[locale],
    listPath: lp(LIST_PATH),
    types: typeLabels(locale),
    purposes: purposeLabels(locale),
    shown: (p: Property) => localizeProperty(p, locale),
  };
}
