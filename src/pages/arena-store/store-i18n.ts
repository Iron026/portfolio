const TEXT: Record<Locale, StoreText> = { pt, en };
export const STORE_BASE = '/demos/arena-store';

/** Textos, rotas e formatadores da Arena Store no idioma da página. */
export function useStore() {
  const { locale, lp } = useLocale();
  const base = lp(STORE_BASE);
  return {
    locale,
    lp,
    t: TEXT[locale],
    paths: { store: base, cart: lp(`${STORE_BASE}/carrinho`), checkout: lp(`${STORE_BASE}/checkout`), product: (id: string) => lp(`${STORE_BASE}/produto/${id}`) },
    cents: (v: number) => formatCents(v, locale),
    categories: categoryLabels(locale),
    sorts: sortLabels(locale),
    payments: paymentLabels(locale),
    size: (s: string) => sizeLabel(s, locale),
    product: (p: Product) => localizeProduct(p, locale),
  };
}

export function restoreNotice(r: { corrupted: boolean; dropped: number; adjusted: number }, locale: Locale) {
  const t = TEXT[locale].restore;
  if (r.corrupted) return t.corrupted;
  const parts: string[] = [];
  if (r.dropped) parts.push(t.dropped(r.dropped));
  if (r.adjusted) parts.push(t.adjusted(r.adjusted));
  return parts.length ? t.joined(parts) : '';
}
