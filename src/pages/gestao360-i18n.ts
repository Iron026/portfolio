const TEXT: Record<Locale, G360Text> = { pt, en };

/** Textos e formatadores do Gestão360 no idioma da página. */
export function useG360() {
  const { locale, intl, lp } = useLocale();
  return {
    locale,
    intl,
    lp,
    t: TEXT[locale],
    money: (v: number) => formatMoney(v, intl),
    compact: (v: number) => moneyCompact(v, intl),
    date: (d: string) => formatDate(d, intl),
    num: (n: number) => n.toLocaleString(intl),
    cat: (c: string) => displayCategory(c, locale),
    desc: (d: string) => displayDescription(d, locale),
  };
}
